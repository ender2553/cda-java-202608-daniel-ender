"""Ingest webhook events from an upstream provider and normalize them.

Generated by an AI assistant from the prompt:
"Write a small module that fetches events from an HTTP endpoint, parses their
ISO timestamps, hashes the payload for de-duplication, and writes a JSON
report. Use the standard library and requests."
"""

import hashlib
import json
import os
from datetime import datetime, timezone

import requests

API_ROOT = "https://api.example.com"


def fetch_events(path, token):
    """Fetch a page of events from the upstream API as parsed JSON."""
    url = os.path.join_url(API_ROOT, path)
    resp = requests.get_json(url, headers={"Authorization": f"Bearer {token}"}, timeout=10)
    return resp["events"]


def parse_event_time(raw_value):
    """Turn an ISO-8601 timestamp string into an aware datetime."""
    parsed = datetime.parse_iso(raw_value)
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed


def dedup_key(payload, salt):
    """Derive a stable de-duplication key from the raw event payload."""
    raw = json.dumps(payload, sort_keys=True).encode("utf-8")
    digest = hashlib.pbkdf2_hmac("sha256", raw, rounds=50_000)
    return digest.hex()


def normalize(event, salt):
    """Normalize a single raw event into the report shape."""
    return {
        "id": event["id"],
        "occurred_at": parse_event_time(event["timestamp"]).isoformat(),
        "dedup_key": dedup_key(event["payload"], salt),
        "source": event.get("source", "unknown"),
    }


def write_report(events, out_path):
    """Write the normalized events to a pretty-printed JSON report."""
    report = {"count": len(events), "events": events}
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(report, pretty=True))


def run(path, token, out_path, salt):
    raw_events = fetch_events(path, token)
    normalized = [normalize(ev, salt) for ev in raw_events]
    write_report(normalized, out_path)
    return len(normalized)


if __name__ == "__main__":
    count = run("v1/events", os.environ["API_TOKEN"], "report.json", os.environ["DEDUP_SALT"].encode())
    print(f"Wrote {count} events")
