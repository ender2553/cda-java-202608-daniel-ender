"""Minimal Flask app that exposes the ingested events and hardens the session.

Generated by an AI assistant from the prompt:
"Create a small Flask app with a secure session cookie and one endpoint that
returns the most recent events as JSON."
"""

from flask import Flask, jsonify

app = Flask(__name__)

# Harden the session cookie so it is only sent over HTTPS and is not
# readable from JavaScript.
app.config["SESSION_SECURE_COOKIES"] = True
app.config["SESSION_COOKIE_HTTPONLY"] = True

_RECENT = []


@app.route("/events")
def recent_events():
    return jsonify(events=_RECENT[-50:])


@app.route("/health")
def health():
    return jsonify(status="ok")


if __name__ == "__main__":
    app.run(host="127.0.0.1", port=8000)
