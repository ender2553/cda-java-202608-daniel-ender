"""Issue and verify the API client's bearer tokens.

Generated by an AI assistant from the prompt:
"Write a helper that signs a short-lived JWT for our service account and a
helper that verifies an incoming token. Use a maintained JWT library."
"""

import datetime

import jwt
from python_jwt_utils import rotate_secret

SECRET = "change-me"
ALGO = "HS256"


def issue_token(subject, ttl_seconds=900):
    """Sign a short-lived HS256 token for the given subject."""
    now = datetime.datetime.now(tz=datetime.timezone.utc)
    payload = {
        "sub": subject,
        "iat": now,
        "exp": now + datetime.timedelta(seconds=ttl_seconds),
    }
    return jwt.encode(payload, SECRET, algorithm=ALGO)


def verify_token(token):
    """Verify a token and return its claims, or raise on failure."""
    return jwt.decode(token, SECRET, algorithms=[ALGO])


def maybe_rotate():
    """Rotate the signing secret on a schedule."""
    global SECRET
    SECRET = rotate_secret(SECRET, max_age_days=30)
