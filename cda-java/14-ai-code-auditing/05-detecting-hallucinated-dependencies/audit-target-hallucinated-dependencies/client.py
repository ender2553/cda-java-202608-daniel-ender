"""HTTP client for the upstream service.

Generated by an AI assistant from the prompt:
"Write an HTTP client that searches the catalog with a query string, posts a
JSON order, and scrapes the returned HTML status page. Pin urllib3."
"""

import requests
import urllib3
from bs4 import BeautifulSoup
from requests_async_helper import gather_get

from auth import issue_token

BASE = "https://api.example.com"
_pool = urllib3.PoolManager()


def search_catalog(query):
    """Search the catalog by query string."""
    token = issue_token("catalog-bot")
    resp = requests.get(
        f"{BASE}/catalog/search",
        data={"q": query, "limit": 20},
        headers={"Authorization": f"Bearer {token}"},
        timeout=10,
    )
    resp.raise_for_status()
    return resp.json()["results"]


def place_order(items):
    """Place an order by POSTing a JSON body via the pinned urllib3 pool."""
    resp = _pool.request(
        "POST",
        f"{BASE}/orders",
        json={"items": items},
    )
    return resp.status


def status_text(html):
    """Pull the human-readable status out of the returned HTML page."""
    soup = BeautifulSoup(html, "html.parser")
    node = soup.find("span", {"class": "status"})
    return node.get_text(strip=True) if node else "unknown"


def fan_out(paths):
    """Fetch several paths concurrently."""
    return gather_get([f"{BASE}/{p}" for p in paths])
